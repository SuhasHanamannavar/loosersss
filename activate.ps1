<#
.SYNOPSIS
  Checkmate Workspace Auto-Activator
  Connects developer environment to Checkmate Control Plane with an active Company API Key.

.DESCRIPTION
  Authenticates developer workstation, verifies key status in AWS DynamoDB,
  syncs post-quantum ML-KEM-768 parameters, and deploys the Company Master Prompt.
#>

[CmdletBinding()]
param(
  [Parameter(Mandatory=$false, Position=0)]
  [string]$ApiKey = $env:CHECKMATE_API_KEY,

  [Parameter(Mandatory=$false)]
  [string]$ControlPlane = "https://checkmateee.vercel.app"
)

$ErrorActionPreference = "Stop"

Write-Host ""
Write-Host "============================================================" -ForegroundColor DarkGray
Write-Host " CHECKMATE · ZERO-TRUST WORKSPACE INITIALIZATION" -ForegroundColor White
Write-Host "============================================================" -ForegroundColor DarkGray

if ([string]::IsNullOrWhiteSpace($ApiKey)) {
  Write-Host "No active API Key found in environment." -ForegroundColor Yellow
  $ApiKey = Read-Host "Enter Company API Key (ck_live_...)"
  if ([string]::IsNullOrWhiteSpace($ApiKey)) {
    Write-Host "[DENY] API Key cannot be empty. Workspace activation aborted." -ForegroundColor Red
    return
  }
}

$ApiKey = $ApiKey.Trim()
$Developer = if ($env:USERNAME) { $env:USERNAME } else { $env:USER }
if (-not $Developer) { $Developer = "developer" }
$HostName = if ($env:COMPUTERNAME) { $env:COMPUTERNAME } else { "workstation" }
$WorkspacePath = (Get-Location).Path

Write-Host "Verifying key with Checkmate Control Plane ($ControlPlane)..." -ForegroundColor Gray

$Payload = @{
  apiKey = $ApiKey
  developer = $Developer
  hostname = $HostName
  workspace = [System.IO.Path]::GetFileName($WorkspacePath)
} | ConvertTo-Json

try {
  $Uri = "$ControlPlane/api/activate"
  $Response = Invoke-RestMethod -Uri $Uri -Method Post -Body $Payload -ContentType "application/json" -TimeoutSec 10
} catch {
  Write-Host ""
  Write-Host "[DENY] Activation Failed: $($_.Exception.Message)" -ForegroundColor Red
  Write-Host "Please check the API key generated by your manager in the Checkmate console." -ForegroundColor DarkGray
  return
}

if (-not $Response.ok -or $Response.status -ne "ACTIVE") {
  Write-Host ""
  Write-Host "[BLOCKED] Key is $($Response.status): $($Response.error)" -ForegroundColor Red
  return
}

# Export environment variables in current PowerShell session
$env:CHECKMATE_API_KEY = $ApiKey
$env:CHECKMATE_STATUS = "ACTIVE"
$env:CHECKMATE_TENANT_ID = $Response.tenantId
$env:CHECKMATE_CONTROL_PLANE = $ControlPlane

# Setup workspace directory and write Master Prompt
$CheckmateDir = Join-Path $WorkspacePath ".checkmate"
if (-not (Test-Path $CheckmateDir)) {
  New-Item -ItemType Directory -Path $CheckmateDir -Force | Out-Null
}

# Write session configuration
$Config = @{
  status = "ACTIVE"
  apiKeyPrefix = if ($ApiKey.Length -gt 12) { $ApiKey.Substring(0, 10) + "..." } else { $ApiKey }
  tenantId = $Response.tenantId
  keyName = $Response.keyName
  developer = $Developer
  activatedAt = $Response.activated_at
  requestId = $Response.requestId
  controlPlane = $ControlPlane
  quantumKemSuite = $Response.kem_suite
} | ConvertTo-Json -Depth 4

Set-Content -Path (Join-Path $CheckmateDir "workspace.json") -Value $Config -Force

# Write Master Prompt
if ($Response.master_prompt) {
  Set-Content -Path (Join-Path $CheckmateDir "MASTER_PROMPT.md") -Value $Response.master_prompt -Force
}

# Also ensure .cursorrules incorporates Checkmate guard if present
$CursorRulesPath = Join-Path $WorkspacePath ".cursorrules"
$RuleHeader = "# Checkmate AI Security Guard Active - Key: $($ApiKey.Substring(0, [Math]::Min(12, $ApiKey.Length)))..."
if (-not (Test-Path $CursorRulesPath)) {
  Set-Content -Path $CursorRulesPath -Value "$RuleHeader`n`nRefer to .checkmate/MASTER_PROMPT.md for zero-trust instructions.`n" -Force
}

Write-Host ""
Write-Host "  STATUS:         ACTIVE (Verified in AWS DynamoDB)" -ForegroundColor Green
Write-Host "  TENANT:         $($Response.tenantId)" -ForegroundColor White
Write-Host "  KEY NAME:       $($Response.keyName)" -ForegroundColor White
Write-Host "  KEM SUITE:      $($Response.kem_suite) (FIPS 203)" -ForegroundColor White
Write-Host "  AUDIT ID:       $($Response.requestId)" -ForegroundColor DarkGray
Write-Host "  MASTER PROMPT:  .checkmate/MASTER_PROMPT.md" -ForegroundColor Cyan
Write-Host "------------------------------------------------------------" -ForegroundColor DarkGray
Write-Host "  Workspace activated. AI agents and tools are now governed." -ForegroundColor Green
Write-Host "============================================================" -ForegroundColor DarkGray
Write-Host ""
